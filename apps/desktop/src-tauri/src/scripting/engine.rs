use rquickjs::{CaughtError, Context, Function, Runtime};

use super::{ConsoleEntry, RequestSnapshot, ScriptContext, ScriptPhase, ScriptResult, TestResult};

const ARK_API_JS: &str = include_str!("ark_api.js");

/// Execute a user script in an isolated QuickJS context.
///
/// The ark API is injected before the user script. After execution,
/// mutations (env/globals/variables changes, test results, console output)
/// are extracted from the JS context and returned as a `ScriptResult`.
pub fn execute_script(
    code: &str,
    context: ScriptContext,
    phase: ScriptPhase,
) -> Result<ScriptResult, String> {
    let rt = Runtime::new().map_err(|e| format!("Failed to create JS runtime: {e}"))?;
    // Limit memory to 32MB and max stack size to 1MB
    rt.set_memory_limit(32 * 1024 * 1024);
    rt.set_max_stack_size(1024 * 1024);

    let ctx = Context::full(&rt).map_err(|e| format!("Failed to create JS context: {e}"))?;

    let ctx_json =
        serde_json::to_string(&context).map_err(|e| format!("Failed to serialize context: {e}"))?;

    let phase_str = match phase {
        ScriptPhase::PreRequest => "pre_request",
        ScriptPhase::PostResponse => "post_response",
    };

    ctx.with(|ctx| {
        let globals = ctx.globals();

        // Inject context JSON and phase as globals
        globals
            .set("__ctx_json", ctx_json)
            .map_err(|e| format!("Failed to set __ctx_json: {e}"))?;
        globals
            .set("__phase_str", phase_str)
            .map_err(|e| format!("Failed to set __phase_str: {e}"))?;

        // Register native crypto helpers (RSA PKCS#1 v1.5 SHA-256 signing).
        // Exposed to scripts as `ark.crypto.rsaSignSha256(pem, data)`.
        // NOTE: the closures intentionally capture NO `Ctx` to avoid a
        // reference cycle (context -> global fn -> closure -> Ctx) that would
        // leak a GC object and abort QuickJS runtime teardown.
        let sign_fn = Function::new(ctx.clone(), native_rsa_sign_sha256);
        globals
            .set("__arkRsaSignSha256", sign_fn)
            .map_err(|e| format!("Failed to register rsa sign fn: {e}"))?;

        let err_fn = Function::new(ctx.clone(), native_rsa_last_error);
        globals
            .set("__arkRsaLastError", err_fn)
            .map_err(|e| format!("Failed to register rsa last-error fn: {e}"))?;

        // Execute ark API setup
        CaughtError::catch(&ctx, ctx.eval::<(), _>(ARK_API_JS))
            .map_err(|e| format!("Failed to initialize ark API: {e}"))?;

        // Execute user script.
        // NOTE: route the error through `CaughtError::catch` so the *real*
        // JavaScript exception message (and stack) is surfaced instead of the
        // opaque "Exception generated by QuickJS" produced by `Error::Exception`.
        CaughtError::catch(&ctx, ctx.eval::<(), _>(code))
            .map_err(|e| format!("Script error: {e}"))?;

        // Extract mutations by serializing __mutations to JSON
        let result_json: String = ctx
            .eval("JSON.stringify(__mutations)")
            .map_err(|e| format!("Failed to extract results: {e}"))?;

        parse_mutations(&result_json, &context)
    })
}

/// RSA PKCS#1 v1.5 signature with SHA-256, equivalent to KJUR's
/// `SHA256withRSA`. Takes a PEM private key (PKCS#8 or PKCS#1) and the raw
/// message string, returns `Some(base64)` on success or `None` on failure
/// (the underlying error is stored and retrievable via
/// `native_rsa_last_error` / `__arkRsaLastError`).
///
/// Exposed to user scripts via QuickJS global `__arkRsaSignSha256`.
fn native_rsa_sign_sha256(pem: String, data: String) -> Option<String> {
    match do_rsa_sign_sha256(&pem, &data) {
        Ok(signature) => Some(signature),
        Err(err) => {
            if let Ok(mut guard) = RSA_LAST_ERROR.lock() {
                *guard = err;
            }
            None
        }
    }
}

/// Returns the message from the most recent failed RSA signing attempt.
/// Exposed to scripts as `__arkRsaLastError`.
fn native_rsa_last_error() -> String {
    RSA_LAST_ERROR
        .lock()
        .map(|guard| guard.clone())
        .unwrap_or_default()
}

/// Most recent RSA signing error, shared between the two native helpers.
static RSA_LAST_ERROR: std::sync::Mutex<String> = std::sync::Mutex::new(String::new());

/// Pure RSA PKCS#1 v1.5 SHA-256 signing, returns base64. No JS context needed.
fn do_rsa_sign_sha256(pem: &str, data: &str) -> Result<String, String> {
    use base64::Engine as _;
    use rsa::pkcs1::DecodeRsaPrivateKey;
    use rsa::pkcs1v15::SigningKey;
    use rsa::pkcs8::DecodePrivateKey;
    use rsa::signature::Signer;
    use rsa::signature::SignatureEncoding;
    use rsa::RsaPrivateKey;
    use sha2::Sha256;

    let der = extract_key_der(pem)?;

    let private_key = RsaPrivateKey::from_pkcs8_der(&der).or_else(|e8| {
        RsaPrivateKey::from_pkcs1_der(&der)
            .map_err(|e1| format!("invalid private key DER (tried PKCS#8, then PKCS#1): pkcs8: {e8}; pkcs1: {e1}"))
    })?;

    let signing_key = SigningKey::<Sha256>::new(private_key);
    let signature = signing_key.sign(data.as_bytes());
    Ok(base64::engine::general_purpose::STANDARD.encode(signature.to_bytes()))
}

/// Extract the DER bytes of a private key from a pasted key string.
///
/// Deliberately lenient: accepts a full PEM (PKCS#8 `BEGIN PRIVATE KEY` or
/// PKCS#1 `BEGIN RSA PRIVATE KEY`), the bare base64 body without markers,
/// arbitrary indentation/CRLF/blank lines, and keys pasted without the
/// trailing marker. The rsa crate's own PEM parser (`pem_rfc7468` +
/// `base64ct`) is extremely strict, so we decode the base64 ourselves and
/// point at the exact offending character on failure.
fn extract_key_der(key: &str) -> Result<Vec<u8>, String> {
    use base64::Engine as _;

    // Keep only the lines between BEGIN/END markers (or the whole input if
    // there are no markers), stripping ALL whitespace.
    let mut body = String::new();
    let mut in_body = false;
    let mut saw_end = false;
    for line in key.lines() {
        let t = line.trim();
        if t.starts_with("-----BEGIN") {
            in_body = true;
            continue;
        }
        if t.starts_with("-----END") {
            in_body = false;
            saw_end = true;
            continue;
        }
        if in_body {
            body.push_str(t.trim());
        }
    }
    let body = if body.is_empty() && !saw_end {
        // No markers at all: treat the entire input as the base64 body.
        key.trim()
    } else {
        &body
    };

    let cleaned: String = body.chars().filter(|c| !c.is_whitespace()).collect();
    if cleaned.is_empty() {
        return Err("invalid private key: key body is empty".to_string());
    }

    // Locate the first character outside the standard base64 alphabet for a
    // precise error message (common: full-width chars from CJK input methods,
    // smart quotes, stray punctuation from truncated copies).
    if let Some((pos, ch)) = cleaned
        .char_indices()
        .find(|(_, c)| !(c.is_ascii_alphanumeric() || *c == '+' || *c == '/' || *c == '='))
    {
        return Err(format!(
            "invalid private key: illegal character {ch:?} (U+{:04X}) at position {pos} of the key body",
            ch as u32
        ));
    }

    let unpadded = cleaned.trim_end_matches('=');
    base64::engine::general_purpose::STANDARD_NO_PAD
        .decode(unpadded)
        .map_err(|e| {
            format!(
                "invalid private key: base64 decode failed ({e}); body length is {} chars",
                unpadded.len()
            )
        })
}

/// Parse the __mutations JSON from JS back into a ScriptResult
fn parse_mutations(json: &str, original_ctx: &ScriptContext) -> Result<ScriptResult, String> {
    let raw: serde_json::Value =
        serde_json::from_str(json).map_err(|e| format!("Failed to parse mutations JSON: {e}"))?;

    // Extract env mutations
    let env_mutations = extract_store_mutations(raw.get("env"));
    let global_mutations = extract_store_mutations(raw.get("globals"));
    let variable_mutations = extract_store_mutations(raw.get("variables"));

    // Extract test results
    let test_results = raw
        .get("tests")
        .and_then(|v| v.as_array())
        .map(|arr| {
            arr.iter()
                .filter_map(|t| {
                    Some(TestResult {
                        name: t.get("name")?.as_str()?.to_string(),
                        passed: t.get("passed")?.as_bool()?,
                        error: t
                            .get("error")
                            .and_then(|e| e.as_str())
                            .map(|s| s.to_string()),
                    })
                })
                .collect()
        })
        .unwrap_or_default();

    // Extract console output
    let console_output = raw
        .get("console")
        .and_then(|v| v.as_array())
        .map(|arr| {
            arr.iter()
                .filter_map(|c| {
                    Some(ConsoleEntry {
                        level: c.get("level")?.as_str()?.to_string(),
                        message: c.get("message")?.as_str()?.to_string(),
                    })
                })
                .collect()
        })
        .unwrap_or_default();

    // Extract request mutations
    let request = if let Some(req) = raw.get("request") {
        RequestSnapshot {
            method: req
                .get("method")
                .and_then(|v| v.as_str())
                .unwrap_or(&original_ctx.request.method)
                .to_string(),
            url: req
                .get("url")
                .and_then(|v| v.as_str())
                .unwrap_or(&original_ctx.request.url)
                .to_string(),
            headers: req
                .get("headers")
                .and_then(|v| v.as_object())
                .map(|obj| {
                    obj.iter()
                        .filter_map(|(k, v)| Some((k.clone(), v.as_str()?.to_string())))
                        .collect()
                })
                .unwrap_or_else(|| original_ctx.request.headers.clone()),
            body: req
                .get("body")
                .map(|v| {
                    if v.is_null() {
                        None
                    } else {
                        v.as_str().map(|s| s.to_string())
                    }
                })
                .unwrap_or_else(|| original_ctx.request.body.clone()),
        }
    } else {
        original_ctx.request.clone()
    };

    Ok(ScriptResult {
        request,
        env_mutations,
        global_mutations,
        variable_mutations,
        test_results,
        console_output,
    })
}

fn extract_store_mutations(value: Option<&serde_json::Value>) -> HashMap<String, Option<String>> {
    value
        .and_then(|v| v.as_object())
        .map(|obj| {
            obj.iter()
                .map(|(k, v)| {
                    let val = if v.is_null() {
                        None
                    } else {
                        Some(v.as_str().unwrap_or("").to_string())
                    };
                    (k.clone(), val)
                })
                .collect()
        })
        .unwrap_or_default()
}

