    #[test]
    fn test_crypto_rsa_sign_tolerates_whitespace_and_crlf() {
        use base64::Engine as _;
        use rand::rngs::OsRng;
        use rsa::pkcs1v15::VerifyingKey;
        use rsa::pkcs8::{EncodePrivateKey, LineEnding};
        use rsa::signature::Verifier;
        use rsa::RsaPrivateKey;
        use sha2::Sha256;

        let mut rng = OsRng;
        let priv_key = RsaPrivateKey::new(&mut rng, 2048).expect("generate key");
        let raw = priv_key
            .to_pkcs8_pem(LineEnding::LF)
            .expect("encode pem")
            .to_string();

        // Indent every line, add CRLF, sprinkle blank lines + surround w/ spaces.
        let indented: String = raw
            .lines()
            .map(|l| format!("    {l}  "))
            .collect::<Vec<_>>()
            .join("\r\n");
        let messy = format!("\r\n  {}  \r\n\r\n", indented);

        let data = "timestamp=1&foo=bar";
        let sig_b64 = do_rsa_sign_sha256(&messy, data).expect("sign despite whitespace");
        let sig = base64::engine::general_purpose::STANDARD
            .decode(&sig_b64)
            .expect("decode b64");

        let verifying_key = VerifyingKey::<Sha256>::new(priv_key.to_public_key());
        let signature = rsa::pkcs1v15::Signature::try_from(sig.as_slice()).expect("sig");
        assert!(verifying_key.verify(data.as_bytes(), &signature).is_ok());
    }

    #[test]
    fn test_crypto_rsa_sign_sha256_end_to_end() {
        use base64::Engine as _;
        use rand::rngs::OsRng;
        use rsa::pkcs1v15::VerifyingKey;
        use rsa::pkcs8::{EncodePrivateKey, LineEnding};
        use rsa::signature::Verifier;
        use rsa::RsaPrivateKey;
        use sha2::Sha256;

        let mut rng = OsRng;
        let priv_key = RsaPrivateKey::new(&mut rng, 2048).expect("generate key");
        let pem = priv_key
            .to_pkcs8_pem(LineEnding::LF)
            .expect("encode pem")
            .to_string();

        let mut ctx = empty_context();
        ctx.request.body = Some(r#"{"foo":"bar"}"#.to_string());

        // Mirror the user-facing pre-request script (with the PEM embedded).
        let script = [
            r#"var requestBody = JSON.parse(ark.request.body || "{}");"#,
            r#"requestBody["timestamp"] = 1700000000000;"#,
            r#"delete requestBody.sign;"#,
            r#"var sortedKeys = Object.keys(requestBody).sort();"#,
            r#"var keyValueString = sortedKeys.map(function (k) { return k + "=" + requestBody[k]; }).join("&");"#,
            &format!("var privkey = `{}`;", pem),
            r#"var sign = ark.crypto.rsaSignSha256(privkey, keyValueString);"#,
            r#"requestBody["sign"] = sign;"#,
            r#"ark.request.setBody(JSON.stringify(requestBody));"#,
        ]
        .join("\n");

        let result = execute_script(&script, ctx, ScriptPhase::PreRequest)
            .expect("script should run without error");

        let body_str = result.request.body.as_ref().expect("body set");
        let body_val: serde_json::Value = serde_json::from_str(body_str).expect("valid json");
        let sign = body_val.get("sign").unwrap().as_str().unwrap();
        assert!(!sign.is_empty());

        // Reconstruct the signed string the same way the script did:
        // it deleted `sign` *before* signing, so exclude it here too.
        // JS string coercion (k + "=" + requestBody[k]) puts string values
        // WITHOUT quotes, so mirror that when flattening scalars.
        fn js_scalar(v: &serde_json::Value) -> String {
            match v {
                serde_json::Value::String(s) => s.clone(),
                serde_json::Value::Number(n) => n.to_string(),
                serde_json::Value::Bool(b) => b.to_string(),
                serde_json::Value::Null => "null".to_string(),
                other => other.to_string(),
            }
        }
        let mut signed_map = body_val.as_object().unwrap().clone();
        signed_map.remove("sign");
        let mut keys: Vec<&String> = signed_map.keys().collect();
        keys.sort();
        let kv: String = keys
            .iter()
            .map(|k| format!("{}={}", k, js_scalar(signed_map.get(*k).unwrap())))
            .collect::<Vec<_>>()
            .join("&");
        let sig = base64::engine::general_purpose::STANDARD
            .decode(sign)
            .expect("decode b64");
        let verifying_key = VerifyingKey::<Sha256>::new(priv_key.to_public_key());
        let signature = rsa::pkcs1v15::Signature::try_from(sig.as_slice()).expect("sig");
        assert!(verifying_key.verify(kv.as_bytes(), &signature).is_ok());
    }

    #[test]
    fn test_crypto_rsa_sign_bare_base64_without_markers() {
        use rand::rngs::OsRng;
        use rsa::pkcs8::{EncodePrivateKey, LineEnding};
        use rsa::RsaPrivateKey;

        let mut rng = OsRng;
        let priv_key = RsaPrivateKey::new(&mut rng, 2048).expect("generate key");
        let pem = priv_key
            .to_pkcs8_pem(LineEnding::LF)
            .expect("encode pem")
            .to_string();

        // Strip the PEM markers: keep only the base64 body.
        let body: String = pem
            .lines()
            .filter(|l| !l.starts_with("-----"))
            .collect::<Vec<_>>()
            .join("");

        let data = "a=1&b=2";
        let sig_from_markers = do_rsa_sign_sha256(&pem, data).expect("pem sign");
        let sig_from_bare = do_rsa_sign_sha256(&body, data).expect("bare base64 sign");
        assert_eq!(sig_from_markers, sig_from_bare);
    }

    #[test]
    fn test_crypto_rsa_sign_missing_end_marker() {
        use rand::rngs::OsRng;
        use rsa::pkcs8::{EncodePrivateKey, LineEnding};
        use rsa::RsaPrivateKey;

        let mut rng = OsRng;
        let priv_key = RsaPrivateKey::new(&mut rng, 2048).expect("generate key");
        let pem = priv_key
            .to_pkcs8_pem(LineEnding::LF)
            .expect("encode pem")
            .to_string();

        // Cut off right after the last base64 line (no END marker).
        let truncated: String = pem
            .lines()
            .filter(|l| !l.starts_with("-----END"))
            .collect::<Vec<_>>()
            .join("\n");

        let data = "a=1&b=2";
        let expected = do_rsa_sign_sha256(&pem, data).expect("full pem sign");
        let actual = do_rsa_sign_sha256(&truncated, data).expect("missing END marker sign");
        assert_eq!(expected, actual);
    }

    #[test]
    fn test_crypto_rsa_sign_illegal_char_is_reported() {
        // A full-width comma (common from CJK IME paste) must be named in the error.
        let bad_key = "-----BEGIN PRIVATE KEY-----\nMIIEvQ，BAD\n-----END PRIVATE KEY-----";
        let err = do_rsa_sign_sha256(bad_key, "data").unwrap_err();
        assert!(err.contains("U+FF0C"), "error should name the char: {err}");
        assert!(err.contains("illegal character"), "error: {err}");
    }
