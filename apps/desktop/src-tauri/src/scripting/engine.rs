    #[test]
    fn test_crypto_rsa_sign_sha256() {
        use base64::Engine as _;
        use rand::rngs::OsRng;
        use rsa::pkcs1v15::VerifyingKey;
        use rsa::pkcs8::{EncodePrivateKey, LineEnding};
        use rsa::signature::Verifier;
        use rsa::RsaPrivateKey;
        use sha2::Sha256;

        let mut rng = OsRng;
        let priv_key = RsaPrivateKey::new(&mut rng, 2048).expect("generate key");
        let pem = priv_key
            .to_pkcs8_pem(LineEnding::LF)
            .expect("encode pem")
            .to_string();

        let data = "timestamp=123&foo=bar";
        let sig_b64 = do_rsa_sign_sha256(&pem, data).expect("sign");
        let sig = base64::engine::general_purpose::STANDARD
            .decode(&sig_b64)
            .expect("decode b64");

        let verifying_key = VerifyingKey::<Sha256>::new(priv_key.to_public_key());
        let signature =
            rsa::pkcs1v15::Signature::try_from(sig.as_slice()).expect("build signature");
        assert!(verifying_key.verify(data.as_bytes(), &signature).is_ok());
    }

